def _write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def _go_project(directory: Path) -> Path:
    _write(directory / "go.mod", GO_MOD)
    _write(directory / ".agent-guardrails.toml", MARKER)
    _write(directory / "calc" / "calc.go", CLEAN)
    _write(directory / "calc" / "calc_test.go", CLEAN_TEST)
    return directory


def _guardrails(
    directory: Path, *arguments: str, env: dict[str, str] | None = None
) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, "-m", "agent_guardrails", "check", *arguments],
        cwd=directory,
        capture_output=True,
        text=True,
        check=False,
        env=env,
    )


def _hook(
    file_path: Path, state_dir: Path, extra_env: dict[str, str] | None = None
) -> subprocess.CompletedProcess[str]:
    payload = json.dumps({"session_id": "go-test", "tool_input": {"file_path": str(file_path)}})
    env = {key: value for key, value in os.environ.items() if key != "CLAUDE_PLUGIN_ROOT"}
    return subprocess.run(
        [str(BASH), str(HOOKS_DIR / "check-edited-file.sh")],
        input=payload,
        capture_output=True,
        text=True,
        check=False,
        env={**env, "TMPDIR": str(state_dir), **(extra_env or {})},
    )


def _output(result: subprocess.CompletedProcess[str]) -> str:
    return result.stdout + result.stderr


@requires_go
def test_clean_go_module_passes(tmp_path: Path) -> None:
    project = _go_project(tmp_path)
    whole = _guardrails(project)
    assert whole.returncode == 0, _output(whole)
    single = _guardrails(project, str(project / "calc" / "calc.go"))
    assert single.returncode == 0, _output(single)


@requires_go
@pytest.mark.parametrize("case", sorted(VIOLATIONS))
def test_go_violation_is_rejected(tmp_path: Path, case: str) -> None:
    rule_id, source = VIOLATIONS[case]
    project = _go_project(tmp_path)
    target = _write(project / "calc" / "bad.go", source)
    result = _guardrails(project, str(target))
    assert result.returncode != 0
    assert rule_id in _output(result)


@requires_go
def test_go_arch_lint_enforces_boundaries(tmp_path: Path) -> None:
    project = _go_project(tmp_path)
    _write(project / ".go-arch-lint.yml", ARCH_CONFIG)
    _write(project / "internal" / "adapters" / "adapters.go", ADAPTERS)
    domain = _write(project / "internal" / "domain" / "domain.go", DOMAIN_USING_ADAPTERS)
    rejected = _guardrails(project)
    assert rejected.returncode != 0
    assert "shouldn't depend on" in _output(rejected)
    domain.write_text(DOMAIN_CLEAN, encoding="utf-8")
    accepted = _guardrails(project)
    assert accepted.returncode == 0, _output(accepted)


