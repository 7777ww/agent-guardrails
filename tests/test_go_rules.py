@requires_go
def test_install_failure_reports_go_output(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setenv("GOPROXY", "off")
    bogus = cli.GoTool("golangci-lint", cli.GOLANGCI_LINT.module, "v0.0.0-missing", "1.26.0")
    with pytest.raises(SystemExit) as failure:
        cli._install_go_tool(str(GO), bogus, tmp_path / "bin" / "golangci-lint")
    message = str(failure.value)
    assert "Go >= 1.26.0" in message
    assert "v0.0.0-missing" in message
    assert "GOPROXY" in message or "module lookup disabled" in message


