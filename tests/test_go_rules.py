def _fake_runners(directory: Path) -> Path:
    real = shutil.which("agent-guardrails")
    _write(directory / "agent-guardrails", "#!/bin/sh\necho stale python-only runner >&2\nexit 1\n")
    _write(
        directory / "uvx",
        '#!/bin/sh\nwhile [ "$1" != agent-guardrails ]; do shift; done\nshift\n'
        f'exec "{real}" "$@"\n',
    )
    for name in ("agent-guardrails", "uvx"):
        (directory / name).chmod(0o755)
    return directory


