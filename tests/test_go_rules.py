def _foreign_platform() -> dict[str, str]:
    host_os, host_arch = cli._go_env(str(GO), "GOHOSTOS", "GOHOSTARCH")
    foreign_os = "linux" if host_os != "linux" else "darwin"
    foreign_arch = "amd64" if host_arch != "amd64" else "arm64"
    return {"GOOS": foreign_os, "GOARCH": foreign_arch}


